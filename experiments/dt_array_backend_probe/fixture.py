#!/usr/bin/env python3
"""Emit a C fixture for the DT-1 selector from the v0.0204 experiment."""
from pathlib import Path
import json, sys
from parse2 import getdefs, strip

BASE = Path('/research/dlm_v0.0204/experiments/deductive_transformer_maru')
M = getdefs(BASE/'src/models.l')
D = getdefs(BASE/'src/data.l')
E = getdefs(BASE/'src/exp_table.l')
P = getdefs(BASE/'src/prior_table.l')
ref = json.loads((BASE/'reference_folds.json').read_text())
fold = M['models'][0]
exp = E['exp-table']
prior = P['prior-log']

def flat(x):
    if isinstance(x, list):
        out=[]
        for y in x: out += flat(y)
        return out
    return [x]

def c1(name, vals, ty='long'):
    vals=list(vals)
    return f'static const {ty} {name}[{max(1,len(vals))}] = {{' + ','.join(str(int(v)) for v in vals) + '};\n'

def c2(name, rows, cols, ty='long'):
    out=[f'static const {ty} {name}[{len(rows)}][{cols}] = {{']
    for r in rows:
        r=list(r)
        assert len(r)==cols, (name,len(r),cols)
        out.append('{' + ','.join(str(int(v)) for v in r) + '},')
    out.append('};\n')
    return '\n'.join(out)

# model shapes
shapes = [('img_w',32,196),('img_b',32,1),('rule_w',32,16),('rule_b',32,1),
          ('in_w',96,32),('in_b',96,1),('out_w',32,32),('out_b',32,1),
          ('l1_w',64,32),('l1_b',64,1),('l2_w',32,64),('l2_b',32,1),
          ('n1g',32,1),('n1b',32,1),('n2g',32,1),('n2b',32,1),('final_w',32,1)]
assert len(fold)==18, len(fold)
lines=['/* auto-generated by fixture.py */','#ifndef DT_FIXTURE_H','#define DT_FIXTURE_H', '#define Q16 65536L']
for (name,rows,cols), t in zip(shapes, fold):
    f=flat(t)
    assert len(f)==rows*cols, (name,len(f),rows*cols)
    lines.append(c2(name, [f[i*cols:(i+1)*cols] for i in range(rows)], cols))
lines.append(c1('final_b', [fold[17]]))
lines.append(c1('exp_table', exp))
lines.append(c1('prior_log', prior))
lines.append(c1('case_bits', D['case-bits'][0]))
lines.append(c1('pool_labels', D['pool-labels']))
lines.append(c2('pool_bits', D['pool-bits'], 196))
lines.append(c1('rule_heads', D['rule-heads']))
maxb=max(len(x) for x in D['rule-bodies'])
rules=[]
for b in D['rule-bodies']:
    b=list(b)+[0]*(maxb-len(b)); rules.append(b)
lines.append(c2('rule_bodies', rules, maxb))
lines.append(c1('rule_lengths', [len(x) for x in D['rule-bodies']]))
lines.append(f'#define RULE_COUNT {len(D["rule-bodies"])}')
lines.append(f'#define MAX_BODY {maxb}')
lines.append(f'#define POOL_COUNT {len(D["pool-bits"])}')
lines.append('#endif')
Path('fixture.h').write_text('\n'.join(lines))
meta={'case':0,'valid':ref[0]['valid'],'selector':ref[0]['selector'],'pick':ref[0]['pick'],
      'head':ref[0]['head'],'label':ref[0]['label'],'n_rules':len(D['rule-bodies'])}
Path('expected.json').write_text(json.dumps(meta,indent=2)+'\n')
print('wrote fixture.h', len('\n'.join(lines)), 'bytes; max_body',maxb)
print(meta)
