#!/usr/bin/env python3
from pathlib import Path
import json
from parse2 import getdefs
BASE=Path('/research/dlm_v0.0204/experiments/deductive_transformer_maru')
M=getdefs(BASE/'src/models.l'); D=getdefs(BASE/'src/data.l'); E=getdefs(BASE/'src/exp_table.l'); P=getdefs(BASE/'src/prior_table.l')
ref=json.loads((BASE/'reference_folds.json').read_text())

def flat(x):
    if isinstance(x,list):
        out=[]
        for y in x: out+=flat(y)
        return out
    return [x]

def c1(name, vals, ty='long'):
    vals=list(vals)
    return f'static const {ty} {name}[{max(1,len(vals))}] = {{'+','.join(str(int(v)) for v in vals)+'};\n'

def c2(name, rows, cols, ty='long'):
    out=[f'static const {ty} {name}[{len(rows)}][{cols}] = {{']
    for r in rows:
        r=list(r); assert len(r)==cols,(name,len(r),cols)
        out.append('{'+','.join(str(int(v)) for v in r)+'},')
    out.append('};\n'); return '\n'.join(out)

shapes=[('img_w',32,196),('img_b',32,1),('rule_w',32,16),('rule_b',32,1),
        ('in_w',96,32),('in_b',96,1),('out_w',32,32),('out_b',32,1),
        ('l1_w',64,32),('l1_b',64,1),('l2_w',32,64),('l2_b',32,1),
        ('n1g',32,1),('n1b',32,1),('n2g',32,1),('n2b',32,1),('final_w',32,1)]
off=0; offsets=[]
for name,r,c in shapes:
    offsets.append((name,off,r,c)); off+=r*c
assert off+1==15425, off
lines=['/* auto-generated by fixture_all.py */','#ifndef DT_ALL_FIXTURE_H','#define DT_ALL_FIXTURE_H','#define Q16 65536L','#define MODEL_SIZE 15425']
lines.append('enum { '+', '.join(f'OFF_{n.upper()}={o}' for n,o,_,_ in offsets)+' };')
models=[]
for fi,fold in enumerate(M['models']):
    vals=[]; k=0
    for name,r,c in shapes:
        f=flat(fold[k]); assert len(f)==r*c,(fi,name,len(f),r*c)
        vals+=f; k+=1
    vals.append(int(fold[17])); assert len(vals)==15425
    models.append(vals)
lines.append(f'static const long models[10][MODEL_SIZE] = {{')
for vals in models:
    lines.append('{'+','.join(str(int(v)) for v in vals)+'},')
lines.append('};\n')
lines.append(c1('exp_table',E['exp-table']))
lines.append(c1('prior_log',P['prior-log']))
lines.append(c2('case_bits',D['case-bits'],196))
lines.append(c2('pool_bits',D['pool-bits'],196))
lines.append(c1('pool_labels',D['pool-labels']))
lines.append(c1('rule_heads',D['rule-heads']))
maxb=max(len(x) for x in D['rule-bodies'])
rules=[list(x)+[0]*(maxb-len(x)) for x in D['rule-bodies']]
lines.append(c2('rule_bodies',rules,maxb))
lines.append(c1('rule_lengths',[len(x) for x in D['rule-bodies']]))
lines.append(f'#define RULE_COUNT {len(D["rule-bodies"])}')
lines.append(f'#define MAX_BODY {maxb}')
lines.append(f'#define POOL_COUNT {len(D["pool-bits"])}')
lines.append('#endif')
Path('fixture_all.h').write_text('\n'.join(lines))
Path('expected_all.json').write_text(json.dumps(ref,indent=2)+'\n')
print('wrote fixture_all.h bytes',len('\n'.join(lines)),'model_size',len(models[0]))
