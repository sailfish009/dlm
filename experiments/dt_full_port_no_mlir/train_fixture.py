#!/usr/bin/env python3
import sys
from pathlib import Path
import torch
ROOT=Path('/research/dlm_v0.0204/experiments/proof_rl_dlm')
sys.path.insert(0,str(ROOT))
import iter_runner as ir
cases=ir.cases; rules=ir.rules
MAXV=8
imgs=[]; valid=[]; feats=[]; ys=[]; nv=[]
for c in range(10):
    img=cases[c][1]
    m=ir.mask(c)
    v=[k for k in range(len(rules)) if m[k].item()>0]
    imgs.append(img); valid.append(v+[0]*(MAXV-len(v))); nv.append(len(v))
    ff=[]; yy=[]
    for k in v:
        ff.append(ir.rv(img,rules[k][0],rules[k][1],'full'))
        yy.append(float(ir.actual.get((c,k),0)))
    feats.append(ff+[[0.0]*16]*(MAXV-len(ff)))
    ys.append(yy+[0.0]*(MAXV-len(yy)))
assert max(nv)<=MAXV
def d2(name,rows,cols,fmt='%g'):
    out=[f'static const double {name}[{len(rows)}][{cols}] = {{']
    for r in rows:
        out.append('{'+','.join(fmt%float(x) for x in r)+'},')
    out.append('};')
    return '\n'.join(out)
def d3(name,arr):
    out=[f'static const double {name}[{len(arr)}][{MAXV}][16] = {{']
    for case in arr:
        out.append('{')
        for row in case: out.append('{'+','.join('%g'%float(x) for x in row)+'},')
        out.append('},')
    out.append('};'); return '\n'.join(out)
lines=['/* auto-generated by train_fixture.py */','#ifndef DT_TRAIN_FIXTURE_H','#define DT_TRAIN_FIXTURE_H','#define MAXV 8']
lines.append(d2('train_img',imgs,196))
lines.append('static const int train_nv[10] = {'+','.join(map(str,nv))+'};')
lines.append('static const int train_valid[10][MAXV] = {')
for v in valid: lines.append('{'+','.join(map(str,v))+'},')
lines.append('};')
lines.append(d3('train_feat',feats))
lines.append(d2('train_y',ys,MAXV))
lines.append('#endif')
Path('train_fixture.h').write_text('\n'.join(lines))
Path('train_meta.json').write_text(__import__('json').dumps({'nv':nv,'valid':valid},indent=2)+'\n')
print('wrote train_fixture.h; nv',nv,'max',max(nv))
