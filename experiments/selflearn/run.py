#!/usr/bin/env python3
"""experiments/selflearn -- the model learns from its own source (v0.0057).

Subject: the DLM package itself.  The model

1. PERCEIVES its own call graph (:func:`dlm.selflearn.call_graph`);
2. INDUCES the governing law from examples it generated by walking its edges
   (positive multi-hop pairs + sampled non-reachable pairs) -- no human hands it
   the transitive rule;
3. RECURSIVELY feeds that law back through the kernel, reifying each certified
   extension as the next relation until the reachability closure is recovered;
4. EVALUATES its own deductive ability -- recall of facts it never observed --
   and compares recursion against a one-composition control on a held-out edge
   split;
5. GROWS its hypothesis vocabulary (:func:`dlm.selflearn.grow_vocabulary`) so
   induction over a fixed alphabet does not plateau (a definitional extension,
   reported separately from the reach gain).

Nothing is asserted here; the kernel decides every fact.
"""
from __future__ import annotations

import argparse
import json
import os
import random
import sys
from typing import Dict, List, Set, Tuple

try:                                            # package import
    from dlm.selflearn import (
        call_graph, induce_composition, self_learn, ground_reach,
        grow_vocabulary, perceive_facts, _compose, _level_rules, _close_one,
    )
except ImportError:                             # direct script
    sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
    from dlm.selflearn import (
        call_graph, induce_composition, self_learn, ground_reach,
        grow_vocabulary, perceive_facts, _compose, _level_rules, _close_one,
    )

VERSION = "0.0.57"


def reach_from(edges: Set[Tuple[str, str]], shape: str, rounds: int = 24) -> set:
    """Recursive self-supervision driven by the INDUCED law shape."""
    rel, pred = set(edges), "calls"
    for k in range(1, rounds + 1):
        nrel = _close_one(rel, pred, f"r{k}", shape)
        if len(nrel - rel) == 0:
            break
        rel, pred = nrel, f"r{k}"
    return rel


def held_out_split(edges, *, frac: float = 0.2, seed: int = 0):
    E = sorted(edges)
    rng = random.Random(seed)
    rng.shuffle(E)
    cut = int(len(E) * frac)
    return set(E[cut:]), set(E[:cut])


def higher_order(library) -> int:
    """Invented rules whose body references an earlier invented predicate."""
    cnt = 0
    for r in library:
        for b in r.body:
            if b.pred.startswith("c") and any(ch.isdigit() for ch in b.pred):
                cnt += 1
                break
    return cnt


def run(root: str, *, rounds: int, max_body: int) -> dict:
    graph = call_graph(root)
    ind = induce_composition(graph.edges)
    sl = self_learn(graph.edges, rounds=rounds)
    one_recall = sl.one_shot_size / sl.ground_size if sl.ground_size else 1.0

    # held-out edge recovery: learn the law from 80% of edges, recover the rest
    train, test = held_out_split(graph.edges, frac=0.2, seed=1)
    holo = ground_reach(train)
    recoverable = {e for e in test if e in holo}
    ho_one = _compose(train) if ind.shape == "compose" else set(train)
    ho_rec = reach_from(train, ind.shape, rounds)
    ho_one_rec = len(recoverable & ho_one) / len(recoverable) if recoverable else 1.0
    ho_rec_rec = len(recoverable & ho_rec) / len(recoverable) if recoverable else 1.0

    vocab = grow_vocabulary(perceive_facts(root), rounds=4, max_body=max_body)
    ho_concepts = higher_order(vocab.library)

    def r2(x):
        return round(x, 4)

    result = {
        "version": VERSION,
        "graph": graph.to_dict(),
        "induction": ind.to_dict(),
        "self_learn": sl.to_dict(),
        "held_out": {
            "edges_held": len(test), "recoverable": len(recoverable),
            "one_shot_recall": r2(ho_one_rec), "recursive_recall": r2(ho_rec_rec),
        },
        "vocabulary": vocab.to_dict(),
        "higher_order_concepts": ho_concepts,
        "self_evaluation": {
            "deduction_before": r2(one_recall),
            "deduction_after": r2(sl.recall),
            "ability_gain": r2(sl.recall - one_recall),
            "features_before": vocab.base_features,
            "features_after": vocab.rounds[-1].features if vocab.rounds else vocab.base_features,
        },
    }
    result["verdicts"] = {
        "law_induced_from_examples": ind.shape == "compose",
        "induction_rejects_negatives": ind.false_pos == 0,
        "induction_discriminates": (ind.true_pos - ind.false_pos) > max(
            (tp - fp for s, tp, fp in ind.candidates if s != "compose"), default=-1),
        "recursion_beats_one_shot": (sl.recall - one_recall) > 0.1,
        "recursive_reaches_closure": sl.recall >= 0.999 and sl.fixed,
        "no_false_derivations": all(r.false == 0 for r in sl.rounds),
        "held_out_recovery": ho_rec_rec > ho_one_rec,
        "vocabulary_grows": (vocab.rounds[-1].features if vocab.rounds else 0) > vocab.base_features,
        "higher_order_concepts": ho_concepts > 0,
    }
    result["all_ok"] = all(result["verdicts"].values())
    return result


def _fmt(rep: dict) -> str:
    g, ind, sl = rep["graph"], rep["induction"], rep["self_learn"]
    se, ho, vo = rep["self_evaluation"], rep["held_out"], rep["vocabulary"]
    lines = []
    lines.append(f"selflearn v{VERSION}  source=dlm  graph: {g['nodes']} nodes, {g['edges']} edges")
    lines.append(f"  induction : law={ind['shape']}  tp={ind['true_pos']} fp={ind['false_pos']} "
                 f"support={ind['support']}")
    lines.append(f"              candidates: " +
                 ", ".join(f"{c['shape']}:{c['tp']}/{c['fp']}" for c in ind["candidates"]))
    lines.append(f"  deduction : one_shot recall={se['deduction_before']:.3f}  "
                 f"recursive recall={se['deduction_after']:.3f}  gain=+{se['ability_gain']:.3f}")
    for r in sl["rounds"]:
        lines.append(f"              round {r['level']}: size={r['size']} new={r['new']} "
                     f"recall={r['recall']:.3f} false={r['false']}")
    lines.append(f"  held-out  : {ho['edges_held']} edges held, {ho['recoverable']} implied; "
                 f"one_shot={ho['one_shot_recall']:.3f} recursive={ho['recursive_recall']:.3f}")
    lines.append(f"  vocab     : features {se['features_before']} -> {se['features_after']}, "
                 f"library={vo['library']}, higher_order={rep['higher_order_concepts']}")
    ok = "PASS" if rep["all_ok"] else "FAIL"
    lines.append(f"  verdicts  : " + ", ".join(f"{k}={'T' if v else 'F'}"
                 for k, v in rep["verdicts"].items()) + f"  -> {ok}")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="recursive self-supervised learning on the model's own source")
    ap.add_argument("--root", default=os.path.join(os.path.dirname(__file__), "..", "..", "dlm"))
    ap.add_argument("--rounds", type=int, default=24)
    ap.add_argument("--max-body", type=int, default=2)
    ap.add_argument("--json", default="")
    ap.add_argument("--offline", action="store_true", help="no network is ever used (accepted for harness parity)")
    args, _ = ap.parse_known_args(argv)

    root = os.path.abspath(args.root)
    rep = run(root, rounds=args.rounds, max_body=args.max_body)

    # determinism check: a second identical run must agree
    rep2 = run(root, rounds=args.rounds, max_body=args.max_body)
    rep["verdicts"]["deterministic"] = (rep2["self_learn"] == rep["self_learn"]
                                        and rep2["vocabulary"] == rep["vocabulary"])
    rep["all_ok"] = all(rep["verdicts"].values())

    print(_fmt(rep))
    if args.json:
        out = os.path.abspath(args.json)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as fh:
            json.dump(rep, fh, indent=2, sort_keys=True)
        print(f"report: {out}")
    return 0 if rep["all_ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())