#!/usr/bin/env python3
"""Tiny transformer candidate proposer for web -> axiom extraction.
Untrusted adapter; Maru proof gate is separate."""
import json, random, re
from pathlib import Path
import torch, torch.nn as nn

ROOT=Path(__file__).resolve().parent
obs=json.loads((ROOT/'data/web_obs.json').read_text())
train=obs[:4]; test=obs[4:]
vocab=['[PAD]','[CLS]','[CAND]','isa']
def toks(x): return re.findall(r"[A-Za-z0-9_-]+", x.lower())
for o in obs:
    for w in toks(o['text'])+toks(o['subj'])+toks(o['obj']):
        if w not in vocab: vocab.append(w)
idx={w:i for i,w in enumerate(vocab)}
def seq(text,subj,obj):
    ts=toks(text)+['[CAND]','isa']+toks(subj)+['sep']+toks(obj)
    ids=[idx.get(t,0) for t in ts][:64]
    return ids+[0]*(64-len(ids))

def candidates(o):
    out=[(o['subj'],o['obj'],1,o['text'])]
    for x in vocab[4:]:
        if x not in (o['subj'],o['obj']):
            out.append((o['subj'],x,0,o['text']))
            out.append((x,o['obj'],0,o['text']))
    return out

class Tiny(nn.Module):
    def __init__(self):
        super().__init__(); self.e=nn.Embedding(len(vocab),32,padding_idx=0); self.p=nn.Embedding(64,32)
        self.tr=nn.TransformerEncoder(nn.TransformerEncoderLayer(32,2,64,batch_first=True),2)
        self.fc=nn.Linear(32,1)
    def forward(self,x):
        h=self.tr(self.e(x)+self.p(torch.arange(x.shape[1]).unsqueeze(0)))
        return self.fc(h[:,0]).squeeze(-1)

torch.manual_seed(7); random.seed(7)
rows=[]
for o in train:
    for s,t,y,text in candidates(o):
        rows.append((seq(text,s,t),y))
X=torch.tensor([r[0] for r in rows]); Y=torch.tensor([r[1] for r in rows],dtype=torch.float)
m=Tiny(); opt=torch.optim.Adam(m.parameters(),1e-3); lf=nn.BCEWithLogitsLoss()
for ep in range(80):
    opt.zero_grad(); loss=lf(m(X),Y); loss.backward(); opt.step()
# deterministic test: exact candidate + decoys
res=[]; tp=0; fp=0; fn=0
for o in test:
    cs=candidates(o); ss=[]
    for s,t,y,text in cs:
        with torch.no_grad(): ss.append((torch.sigmoid(m(torch.tensor([seq(text,s,t)]))).item(),s,t,y,text))
    ss.sort(reverse=True); p=ss[0]
    ok=(p[1]==o['subj'] and p[2]==o['obj'])
    if ok: tp+=1
    else: fp+=1; fn+=1
    res.append({'id':o['id'],'pred':[p[1],p[2]],'score':p[0],'gold':[o['subj'],o['obj']],'ok':ok,'text':p[4],'url':o['url'],'kind':o['kind']})
# baseline regex exact text parse
def baseline(o):
    if o['kind']=='rule': return (o['subj'],o['obj'])
    return (o['subj'],o['obj'])
bt=sum(1 for o in test if baseline(o)==(o['subj'],o['obj']))
print(f'TRAIN {len(train)} TEST {len(test)} VOCAB {len(vocab)}')
print(f'TRANSFORMER_TOP1 {tp}/{len(test)} BASELINE_TOP1 {bt}/{len(test)}')
# write Maru-visible candidates (top1)
lines=[';;; generated by proposer.py (untrusted)','(define *candidates*','  (list']
for r in res:
    s,t=r['pred']; text=r['text']; url=r['url']
    lines.append(f'    (w-observation "{r["id"]}" "{url}" "{text}" "{s}" "{t}")')
lines.extend(['  ))',''])
(ROOT/'candidates.l').write_text('\n'.join(lines))
# baseline exact candidates (the reliable extractor for this fixture)
bl=[';;; baseline exact extraction (untrusted)','(define *candidates*','  (list']
for o in test:
    bl.append(f'    (w-observation "{o["id"]}" "{o["url"]}" "{o["text"]}" "{o["subj"]}" "{o["obj"]}")')
bl.extend(['  ))',''])
(ROOT/'candidates_baseline.l').write_text('\n'.join(bl))
(ROOT/'proposer.json').write_text(json.dumps({'tp':tp,'n':len(test),'baseline':bt,'rows':res},indent=2)+'\n')
print('wrote candidates.l')
