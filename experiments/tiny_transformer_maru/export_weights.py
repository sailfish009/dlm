#!/usr/bin/env python3
"""Export the PyTorch checkpoint to Q16 S-expressions for Maru."""
import json
from pathlib import Path
import torch
import reference as R

ROOT = Path(__file__).resolve().parent
Q = 16
ONE = 1 << Q

def q16(x):
    return int(round(float(x) * ONE))

def sexp_list(vals):
    return "(list " + " ".join(str(v) for v in vals) + ")"

def sexp_matrix(mat):
    rows = [sexp_list(row) for row in mat]
    return "(list " + " ".join(rows) + ")"

def sym(key):
    return "w-" + key.replace(".", "-").replace("_", "-")

def main():
    model = R.load_checkpoint(ROOT / "checkpoint.pt")
    sd = model.state_dict()
    lines = []
    lines.append(";;; auto-generated by export_weights.py — Q16 fixed point")
    lines.append(f"(define q-scale {ONE})")
    lines.append(f"(define d-model {R.D})")
    lines.append(f"(define n-heads {R.HEADS})")
    lines.append(f"(define d-ff {R.D_FF})")
    lines.append(f"(define n-layers {R.NUM_LAYERS})")
    lines.append(f"(define max-length {R.MAX_LENGTH})")
    lines.append("(define bos-id %d)" % R.BOS)
    lines.append("(define eos-id %d)" % R.EOS)
    lines.append("(define source-words (list %s))" % " ".join('"%s"' % w for w in R.SOURCE_WORDS))
    lines.append("(define target-words (list %s))" % " ".join('"%s"' % w for w in R.TARGET_WORDS))
    meta = {}
    for key, tensor in sd.items():
        arr = tensor.detach().cpu()
        name = sym(key)
        if arr.ndim == 1:
            body = sexp_list(q16(v) for v in arr.tolist())
        elif arr.ndim == 2:
            body = sexp_matrix([[q16(v) for v in row] for row in arr.tolist()])
        else:
            raise ValueError((key, arr.shape))
        lines.append(f"(define {name} {body})")
        meta[name] = list(arr.shape)
    (ROOT / "src" / "weights.l").write_text("\n".join(lines) + "\n")
    (ROOT / "weights_meta.json").write_text(json.dumps(meta, indent=2) + "\n")

    # PyTorch reference outputs for verification
    outs = []
    for en, _ in R.EN_CN_PAIRS:
        text, trace = R.greedy(model, en, return_logits=True)
        src_ids = [R.SOURCE_IDS[w] for w in en.split()]
        outs.append({"source": en, "source_ids": src_ids, "translation": text,
                     "logits": trace})
    (ROOT / "reference_out.json").write_text(json.dumps(outs, ensure_ascii=False, indent=2) + "\n")
    print(f"wrote weights.l ({len(sd)} tensors, {sum(t.numel() for t in sd.values())} params)")
    print(f"wrote reference_out.json ({len(outs)} sentences)")

if __name__ == '__main__':
    main()
