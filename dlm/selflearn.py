# --------------------------------------------------------------------------- #
# perception: the model reading its own source (generic, no domain knowledge)
# --------------------------------------------------------------------------- #
def _defined_names(root: str) -> Tuple[Dict[str, set], Dict[str, ast.AST]]:
    trees: Dict[str, ast.AST] = {}
    by_name: Dict[str, set] = {}
    for fname in sorted(os.listdir(root)):
        if not fname.endswith(".py") or fname == "__init__.py":
            # keep __init__ too -- it defines the kernel surface
            pass
        if not fname.endswith(".py"):
            continue
        mod = fname[:-3]
        try:
            tree = ast.parse(open(os.path.join(root, fname), encoding="utf-8").read())
        except SyntaxError:
            continue
        trees[mod] = tree
        for n in ast.walk(tree):
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
                by_name.setdefault(n.name, set()).add(f"{mod}.{n.name}")
    return by_name, trees


def perceive_facts(root: str) -> set:
    """Generic structural facts about the Python source under ``root``.

    Predicates name no library and no dataset: ``defined``/``private``/
    ``dunder``/``documented``/``method`` (unary, subject = ``module.func``) and
    ``calls`` (binary, subject = caller, constant = callee short name).
    """
    by_name, trees = _defined_names(root)
    facts: set = set()
    for mod, tree in trees.items():
        for n in ast.walk(tree):
            if not isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            q = f"{mod}.{n.name}"
            facts.add(Atom("defined", (Const(q),)))
            if n.name.startswith("__") and n.name.endswith("__"):
                facts.add(Atom("dunder", (Const(q),)))
            elif n.name.startswith("_"):
                facts.add(Atom("private", (Const(q),)))
            if ast.get_docstring(n):
                facts.add(Atom("documented", (Const(q),)))
            if n.args.args and n.args.args[0].arg in ("self", "cls"):
                facts.add(Atom("method", (Const(q),)))
            for x in ast.walk(n):
                if isinstance(x, ast.Call):
                    nm = getattr(x.func, "id", None) or getattr(x.func, "attr", None)
                    if nm:
                        facts.add(Atom("calls", (Const(q), Const(nm))))
    return facts


@dataclass(frozen=True)
class CallGraph:
    nodes: Tuple[str, ...]
    edges: frozenset          # frozenset of (caller, callee) qualified names

    def to_dict(self) -> dict:
        return {"nodes": len(self.nodes), "edges": len(self.edges)}


def call_graph(root: str) -> CallGraph:
    """Intra-package call graph: ``F -> G`` only when both are defined under ``root``."""
    by_name, trees = _defined_names(root)
    edges: set = set()
    nodes: set = set()
    for mod, tree in trees.items():
        for n in ast.walk(tree):
            if not isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            src = f"{mod}.{n.name}"
            nodes.add(src)
            for x in ast.walk(n):
                if isinstance(x, ast.Call):
                    nm = getattr(x.func, "id", None) or getattr(x.func, "attr", None)
                    if nm in by_name:
                        for tgt in by_name[nm]:
                            if tgt != src:
                                edges.add((src, tgt))
                                nodes.add(tgt)
    return CallGraph(tuple(sorted(nodes)), frozenset(edges))


# --------------------------------------------------------------------------- #
# induction: learn the composition law from examples (not given)
# --------------------------------------------------------------------------- #
def _compose(E: set) -> set:
    by_src: Dict[str, set] = {}
    for a, b in E:
        by_src.setdefault(a, set()).add(b)
    out = set()
    for a, b in E:
        for c in by_src.get(b, ()):
            out.add((a, c))
    return out


def _swap(E: set) -> set:
    """``h(X,Z) :- rel(X,Y), rel(Z,Y)`` -- share the SECOND argument."""
    by_second: Dict[str, set] = {}
    for a, b in E:
        by_second.setdefault(b, set()).add(a)
    out = set()
    for a, b in E:
        for z in by_second.get(b, ()):
            out.add((a, z))
    return out


def _reverse(E: set) -> set:
    """``h(X,Z) :- rel(Y,X), rel(Y,Z)`` -- share the FIRST argument."""
    by_first: Dict[str, set] = {}
    for a, b in E:
        by_first.setdefault(a, set()).add(b)
    out = set()
    for a, b in E:                       # (a,b) as rel(Y,X)? here Y=a, X=b
        for c in by_first.get(a, ()):
            out.add((b, c))
    return out


_SHAPES = {"compose": _compose, "swap": _swap, "reverse": _reverse,
           "identity": lambda E: set(E)}


@dataclass(frozen=True)
class InductionResult:
    shape: str
    rule: Rule
    true_pos: int
    false_pos: int
    support: int
    candidates: Tuple[Tuple[str, int, int], ...]   # (shape, tp, fp)

    def to_dict(self) -> dict:
        return {"shape": self.shape, "true_pos": self.true_pos,
                "false_pos": self.false_pos, "support": self.support,
                "candidates": [{"shape": s, "tp": tp, "fp": fp}
                               for s, tp, fp in self.candidates]}


def induce_composition(edges, *, rel: str = "calls", sample: int = 400,
                       negatives: int = 400, seed: int = 0) -> InductionResult:
    """Search candidate 2-literal bodies and pick the law that best fits examples.

    Positives are multi-hop pairs the model generated by walking its own edges;
    negatives are sampled non-reachable pairs over the same node set.  The
    correct composition ``h(X,Z) :- rel(X,Y), rel(Y,Z)`` is selected on evidence,
    not supplied.
    """
    E = set(edges)
    nodes = sorted({a for e in E for a in e})
    rng = random.Random(seed)
    P = _compose(E)
    Plist = sorted(P)
    if sample and len(Plist) > sample:
        Plist = rng.sample(Plist, sample)
    Pset = set(Plist)
    N = set()
    tries = 0
    while len(N) < negatives and tries < negatives * 50:
        tries += 1
        a, b = rng.choice(nodes), rng.choice(nodes)
        if (a, b) not in P:               # a non-composition pair is a negative
            N.add((a, b))

    scored: List[Tuple[str, int, int]] = []
    for shape in sorted(_SHAPES):
        derived = _SHAPES[shape](E)
        tp = len(derived & Pset)
        fp = len(derived & N)
        scored.append((shape, tp, fp))
    best = max(scored, key=lambda t: (t[1] - t[2], t[1], -len(t[0])))
    x, y, z = Var("?x"), Var("?y"), Var("?z")
    bodies = {
        "compose": (Atom(rel, (x, y)), Atom(rel, (y, z))),
        "swap": (Atom(rel, (x, y)), Atom(rel, (z, y))),
        "reverse": (Atom(rel, (y, x)), Atom(rel, (y, z))),
        "identity": (Atom(rel, (x, z)),),
    }
    rule = Rule(Atom("reach", (x, z)), bodies[best[0]], name=f"reach_{best[0]}")
    return InductionResult(best[0], rule, best[1], best[2], len(P),
                           tuple(scored))


# --------------------------------------------------------------------------- #
# recursive self-supervision: feed the induced law back through the kernel
# --------------------------------------------------------------------------- #
def _atoms(pairs, pred: str) -> set:
    return {Atom(pred, (Const(a), Const(b))) for a, b in pairs}


def _level_rules(shape: str, cur: str, nxt: str) -> Tuple[Rule, ...]:
    x, y, z = Var("?x"), Var("?y"), Var("?z")
    inherit = Rule(Atom(nxt, (x, y)), (Atom(cur, (x, y)),), name=f"{nxt}_inherit")
    if shape == "compose":
        compose = Rule(Atom(nxt, (x, z)), (Atom(cur, (x, y)), Atom(cur, (y, z))),
                       name=f"{nxt}_compose")
        return (inherit, compose)
    return (inherit,)


def _close_one(pairs: set, cur: str, nxt: str, shape: str) -> set:
    kb = KnowledgeBase(_atoms(pairs, cur))
    for r in _level_rules(shape, cur, nxt):
        kb.add_rule(r)
    return {(a.args[0].name, a.args[1].name)
            for a in closure(kb) if a.pred == nxt}


@dataclass(frozen=True)
class LearnRound:
    level: int
    size: int
    new: int
    recall: float
    false: int

    def to_dict(self) -> dict:
        return {"level": self.level, "size": self.size, "new": self.new,
                "recall": self.recall, "false": self.false}


@dataclass
class SelfLearnResult:
    shape: str
    rounds: List[LearnRound]
    relation: set
    ground_size: int
    one_shot_size: int
    fixed: bool

    @property
    def recall(self) -> float:
        return len(self.relation) / self.ground_size if self.ground_size else 1.0

    def to_dict(self) -> dict:
        return {
            "shape": self.shape, "fixed": self.fixed,
            "ground": self.ground_size, "one_shot": self.one_shot_size,
            "one_shot_recall": (self.one_shot_size / self.ground_size
                                if self.ground_size else 1.0),
            "recursive": len(self.relation), "recursive_recall": self.recall,
            "rounds": [r.to_dict() for r in self.rounds],
        }


def ground_reach(edges) -> set:
    """Ground-truth reachability (evaluation only; the model never sees it)."""
    return reachability(list(edges))


def self_learn(edges, *, rounds: int = 24, seed: int = 0) -> SelfLearnResult:
    """Induce the law, then bootstrap it to a fixpoint (the self-supervision)."""
    E = set(edges)
    ind = induce_composition(E, seed=seed)
    ground = ground_reach(E)
    one = _compose(E) if ind.shape == "compose" else set(E)

    rel = set(E)
    pred = "calls"
    recs: List[LearnRound] = []
    fixed = False
    for k in range(1, rounds + 1):
        nxt = f"r{k}"
        nrel = _close_one(rel, pred, nxt, ind.shape)
        new = len(nrel - rel)
        recs.append(LearnRound(k, len(nrel), new,
                               len(nrel & ground) / len(ground) if ground else 1.0,
                               len(nrel - ground)))
        rel, pred = nrel, nxt
        if new == 0:
            fixed = True
            break
    return SelfLearnResult(ind.shape, recs, rel, len(ground), len(one), fixed)


# --------------------------------------------------------------------------- #
# hypothesis-vocabulary growth (why a fixed alphabet plateaus)
# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class Invention:
    round: int
    concepts: int
    features: int
    new_atoms: int
    corpus: int

    def to_dict(self) -> dict:
        return {"round": self.round, "concepts": self.concepts,
                "features": self.features, "new_atoms": self.new_atoms,
                "corpus": self.corpus}


@dataclass
class VocabularyResult:
    rounds: List[Invention]
    library: Tuple[Rule, ...]
    facts: frozenset
    base_features: int

    def to_dict(self) -> dict:
        return {"base_features": self.base_features, "library": len(self.library),
                "final_features": self.rounds[-1].features if self.rounds else self.base_features,
                "rounds": [r.to_dict() for r in self.rounds]}


def _rename(rep, r: int) -> List[Rule]:
    out: List[Rule] = []
    for i, c in enumerate(rep.concepts):
        name = f"c{r}_{i}"
        out.append(Rule(Atom(name, (Var("X"),)), c.rule.body, name=name))
    return out


def _derive(rules: Sequence[Rule], facts: set) -> set:
    kb = KnowledgeBase(set(facts))
    for rule in rules:
        kb.add_rule(rule)
    return {a for a in closure(kb) if a.pred.startswith("c")}


def grow_vocabulary(facts, *, rounds: int = 6, min_support: int = 2,
                    max_body: int = 3, max_concepts: int = 8) -> VocabularyResult:
    """Recursively invent predicates so the hypothesis language keeps growing."""
    cur = set(facts)
    library: List[Rule] = []
    recs: List[Invention] = []
    base_features = 0
    for r in range(rounds):
        rep = induce_concepts(cur, min_support=min_support, max_body=max_body,
                              max_concepts=max_concepts)
        if r == 0:
            base_features = len(rep.features)
        new_rules = _rename(rep, r)
        new_atoms = _derive(new_rules, cur)
        library.extend(new_rules)
        cur |= new_atoms
        recs.append(Invention(r, len(rep.concepts), len(rep.features),
                              len(new_atoms), len(cur)))
        if not rep.concepts:
            break
    return VocabularyResult(recs, tuple(library), frozenset(cur), base_features)