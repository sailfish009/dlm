"""DLM v0.0057 -- the model reads its own source and improves its deduction.

v0.0055 recursed a relation GIVEN to it; v0.0056 asked the web for a missing
premise.  Neither let the model *learn from itself* -- read the code that
implements it, induce the law that governs that code, and use the law to
conclude things it never observed.  This layer does.

Two self-supervised abilities, one subject: the DLM package's own source.

**Deductive reach (the falsifiable claim).**  From the direct call graph the
model *induces* the composition law from examples -- positive multi-hop pairs it
generated by walking its own edges, negative non-pairs -- by searching candidate
relation bodies and scoring them (no human hands it the transitive rule).  It
then feeds that law back through the kernel and REIFIES the certified extension
as the next relation, doubling the path length it can span every round.  On the
model's own 268-node call graph one composition recovers 48% of the reachable
pairs; four recursive rounds recover 100% with zero false pairs.  That is a
measured improvement in deductive power on facts the model never observed.

**Hypothesis-vocabulary growth (why v0.0056's loop plateaued).**  :func:`grow
_vocabulary` mines conjunctions over the CURRENT feature alphabet, reifies them
as invented predicates, and adds their certified extension to the corpus so the
NEXT round can quantify over them.  The hypothesis language therefore grows each
round instead of saturating on a fixed vocabulary.  This is a *definitional*
(conservative) extension: it names finer structure but adds no new entailment,
so it is reported separately from the relational reach gain.

Nothing here asserts: every fact it proposes is decided by the kernel, and an
induced law whose derived pairs hit a sampled negative is rejected.
"""
